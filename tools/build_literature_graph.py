"""Rebuild literature-graph.js from the Obsidian vault.

Usage:  python tools/build_literature_graph.py "C:/Users/vsz472/Documents/Obsidian Vault/Vault"

Reads the literature notes (References/Literature Source Notes) and the concept
notes (Thoughts and other notes/Concept notes), follows the [[wiki links]]
between them, and writes the graph that the home page draws.
Notes with no links are left out, like Obsidian's "hide orphans".
"""
import json, os, re, sys

vault = sys.argv[1] if len(sys.argv) > 1 else "."
LIT = os.path.join("References", "Literature Source Notes")
CONCEPT = os.path.join("Thoughts and other notes", "Concept notes")

def front(text):
    """Pull author, year and title out of the note's YAML header."""
    m = re.match(r"---\s*\n(.*?)\n---", text, re.S)
    head = m.group(1) if m else ""
    def field(k):
        f = re.search(rf"^{k}:\s*\"?(.*?)\"?\s*$", head, re.M)
        return f.group(1).strip() if f else ""
    a = re.search(r"^authors:\s*\n\s*-\s*\"?([^,\"\n]+)", head, re.M)
    return (a.group(1).strip() if a else ""), field("year"), field("title")

def label_for(name, text, kind):
    if kind == "concept":
        return name, ""
    author, year, title = front(text)
    if not (author and year):
        m = re.match(r"@([a-z][a-z\-]*?)(?=[A-Z0-9]).*?((?:19|20)\d{2})\D*$", name)
        if m:
            author = author or m.group(1)[:1].upper() + m.group(1)[1:]
            year = year or m.group(2)
    if author and " " in author and re.match(r"([A-Z]\.\s*)+", author):
        author = author.split()[-1]          # "A. P. Nutman" -> "Nutman"
    if re.match(r"https?:|\S+\.\S+/", title) or title.lower().endswith(".pdf"):
        title = ""                           # a pasted URL is not a title
    if not title and not (author and year):  # fall back to the file name, tidied
        base = re.sub(r"\.pdf$|pdf$", "", name.lstrip("@"), flags=re.I)
        base = re.sub(r"(?<=[a-z])(?=[A-Z])", " ", base)
        base = re.sub(r"(?<=[A-Za-z])(?=(?:19|20)\d{2})", " ", base)
        m = re.search(r"(?:19|20)\d{2}", base)
        if m:
            year = m.group(0)
            author = re.split(r"\s+et al|\s*(?:19|20)\d{2}", base)[0].strip()
            author = author[:1].upper() + author[1:]
        else:
            return base.strip()[:1].upper() + base.strip()[1:], title
    if author and year:
        return f"{author} {year}", title
    if title:
        short = " ".join(title.split()[:5])
        return (short + "\u2026" if len(title.split()) > 5 else short), title
    return name.lstrip("@").strip(), title

notes = {}  # lowercased name -> node
for sub, kind in ((LIT, "paper"), (CONCEPT, "concept")):
    for dp, _, fn in os.walk(os.path.join(vault, sub)):
        for f in fn:
            if not f.endswith(".md"):
                continue
            name = f[:-3]
            topic = os.path.basename(dp)
            topic = re.sub(r"^\d+\s*", "", topic) if kind == "paper" else "Concept note"
            notes[name.lower()] = {"name": name, "path": os.path.join(dp, f), "kind": kind, "topic": topic}

edges = set()
for key, n in notes.items():
    text = open(n["path"], encoding="utf-8", errors="ignore").read()
    n["label"], n["title"] = label_for(n["name"], text, n["kind"])
    for target in re.findall(r"\[\[([^\]|#^]+)", text):
        t = os.path.basename(target.strip()).lower()
        if t.endswith(".md"):
            t = t[:-3]
        if t in notes and t != key:
            edges.add(tuple(sorted((key, t))))

linked = sorted({k for e in edges for k in e}, key=lambda k: (notes[k]["kind"] != "concept", k))
index = {k: i for i, k in enumerate(linked)}
data = {
    "nodes": [{"l": notes[k]["label"], "k": notes[k]["kind"][0], "t": notes[k]["topic"], "p": notes[k]["title"]} for k in linked],
    "links": sorted([index[a], index[b]] for a, b in edges),
}
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "literature-graph.js")
with open(out, "w", encoding="utf-8") as fh:
    fh.write("/* Generated by tools/build_literature_graph.py from the Obsidian vault. */\n")
    fh.write("window.LIT_GRAPH = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
papers = sum(1 for k in linked if notes[k]["kind"] == "paper")
print(f"{papers} papers, {len(linked) - papers} concept notes, {len(edges)} links -> {os.path.normpath(out)}")
